INLINE_TAG_RE = re.compile(r"\{[^{}]*\}")
WORD_BOUNDARY_L = r"(?<![A-Za-zÁÉÍÓÚÜÑáéíóúüñ'])"
WORD_BOUNDARY_R = r"(?![A-Za-zÁÉÍÓÚÜÑáéíóúüñ'])"


def apply_outside_tags(text: str, fn: Callable[[str], str]) -> str:
    """Apply transformation function `fn` only to text outside `{...}` inline tags."""
    parts = INLINE_TAG_RE.split(text)
    tags = INLINE_TAG_RE.findall(text)
    out: list[str] = []
    for i, part in enumerate(parts):
        out.append(fn(part))
        if i < len(tags):
            out.append(tags[i])
    return "".join(out)


def load_accepted_words(config_path: Path | None = None) -> set[str]:
    """Load the project dictionary of accepted words and expressions."""
    if config_path is None:
        config_path = Path(__file__).resolve().parent.parent.parent / "translation" / "config" / "accepted-words.txt"
    if not config_path.exists():
        return set()
    words = set()
    for line in config_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        words.add(line)
    return words


